/** A group, a group set or “retail venues”, alone or with a shop role (“…ที่มี…”); null when unknown. */
function subject(th) {
  const s = String(th || '').trim();
  if (SUBJECT_EN[s]) return SUBJECT_EN[s];
  const m = /^(.+)ที่มี(.+)$/.exec(s);
  if (!m || !SUBJECT_EN[m[1]]) return null;
  if (ROLE_EN[m[2]]) return `${SUBJECT_EN[m[1]]} with ${ROLE_EN[m[2]].toLowerCase()}`;
  if (m[2] === 'พื้นที่สำหรับสัตว์เลี้ยง') return `${SUBJECT_EN[m[1]]} with a pet area`;
  return null;
}
/** “ตลาด ไฮเปอร์/ซูเปอร์มาร์เก็ต และในโครงการ” → “markets, hyper/supermarkets and retail spaces in developments”. */
function groupList(th) {
  const items = String(th || '').split(/ และ| /).filter(Boolean).map(x => SUBJECT_EN[x] || null);
  if (!items.length || items.some(x => x == null)) return null;
  return items.length > 1 ? `${items.slice(0, -1).join(', ')} and ${items[items.length - 1]}` : items[0];
}
